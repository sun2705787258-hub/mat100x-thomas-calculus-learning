import fs from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function walk(directory, relative = "") {
  const files = [];
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    if ([".git", "node_modules", "dist"].includes(entry.name)) continue;
    const next = path.join(relative, entry.name);
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full, next)));
    else files.push(next);
  }
  return files;
}

const sha256 = async (file) =>
  crypto.createHash("sha256").update(await fs.readFile(file)).digest("hex").toUpperCase();

const classify = (file) => {
  const value = file.replaceAll("\\", "/");
  if (value.startsWith(".github/")) return ["workflow", "CI / release automation"];
  if (value.startsWith("assets/vendor/")) return ["third-party-asset", "offline runtime dependency"];
  if (value.startsWith("assets/")) return ["shared-asset", "site runtime"];
  if (value.startsWith("chapters/")) return ["canonical-chapter", "learner site"];
  if (value.startsWith("batches/")) return ["batch-archive", "historical acceptance snapshot"];
  if (value.startsWith("pdf/")) return ["pdf", "GitHub Release asset"];
  if (value.startsWith("scripts/")) return ["automation", "CI and release tooling"];
  if (value.startsWith("quality/")) return ["quality-evidence", "quality dashboard"];
  if (value.startsWith("data/")) return ["runtime-data", "offline search and chapter metadata"];
  if (value.startsWith("docs/") || /\.md$/i.test(value)) return ["documentation", "repository or published docs"];
  if (["guide", "overview", "terminology", "exercises", "review", "reference", "downloads", "source", "archive"].some((prefix) => value.startsWith(`${prefix}/`))) {
    return ["learning-module", "learner site"];
  }
  return ["repository-file", "repository support"];
};

const entries = [];
for (const file of (await walk(root)).sort()) {
  const normalized = file.replaceAll("\\", "/");
  const stat = await fs.stat(path.join(root, file));
  const [type, destination] = classify(file);
  entries.push({
    path: normalized,
    type,
    destination,
    bytes: stat.size,
    sha256: await sha256(path.join(root, file)),
  });
}

const report = {
  schemaVersion: "thomas-repository-inventory-v1",
  summary: {
    files: entries.length,
    bytes: entries.reduce((sum, entry) => sum + entry.bytes, 0),
    html: entries.filter((entry) => entry.path.endsWith(".html")).length,
    pdfs: entries.filter((entry) => entry.path.endsWith(".pdf")).length,
  },
  entries,
};
await fs.mkdir(path.join(root, "quality"), { recursive: true });
await fs.writeFile(
  path.join(root, "quality", "artifact-inventory.json"),
  `${JSON.stringify(report, null, 2)}\n`,
);

const rows = entries
  .map(
    (entry) =>
      `| \`${entry.path}\` | ${entry.type} | ${entry.destination} | ${entry.bytes} | \`${entry.sha256}\` |`,
  )
  .join("\n");
await fs.writeFile(
  path.join(root, "ARTIFACT_INVENTORY.md"),
  `# Repository Artifact Inventory

Generated by \`npm run inventory\`.

## Summary

| Item | Value |
|---|---:|
| Files | ${report.summary.files} |
| HTML pages | ${report.summary.html} |
| PDFs | ${report.summary.pdfs} |
| Total bytes | ${report.summary.bytes} |

## Entries

| Path | Type | Destination | Bytes | SHA-256 |
|---|---|---|---:|---|
${rows}
`,
);
